#!/usr/bin/env python3
"""Generate src/presentation/music_glyphs.rs from the Bravura music font.

Usage:
    pip install fonttools
    python3 tools/extract_music_glyphs.py path/to/Bravura.otf > src/presentation/music_glyphs.rs

Bravura (c) 2015 Steinberg Media Technologies GmbH, SIL Open Font License 1.1.
See LICENSES/Bravura-OFL.txt. Coordinates are written in staff spaces
(1 space = 250 font units, since Bravura uses 1000 units per em and 4 spaces per em).
"""
import sys

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

SPACE_UNITS = 250.0

# SMuFL code points
GLYPHS = [
    ("TREBLE_CLEF", 0xE050, "gClef: origin on the G line"),
    ("BASS_CLEF", 0xE062, "fClef: origin on the F line"),
    ("WHOLE_NOTEHEAD", 0xE0A2, "noteheadWhole: origin at the vertical centre of the head, left edge at x = 0"),
    ("HALF_NOTEHEAD", 0xE0A3, "noteheadHalf: origin at the vertical centre of the head, left edge at x = 0"),
    ("SHARP", 0xE262, "accidentalSharp: origin at the centre of the sign"),
    ("FLAT", 0xE260, "accidentalFlat: origin on the line the flat's bowl sits on"),
    ("NATURAL", 0xE261, "accidentalNatural: origin at the centre of the sign"),
]
DIGITS = [(f"TIME_SIG_{n}", 0xE080 + n) for n in range(10)]


def fmt(value):
    text = f"{value / SPACE_UNITS:.4f}".rstrip("0").rstrip(".")
    if text in ("", "-0"):
        text = "0"
    if "." not in text:
        text += ".0"
    return text


def outline(font, glyph_set, cmap, code_point):
    name = cmap[code_point]
    pen = RecordingPen()
    glyph_set[name].draw(pen)
    ops = []
    for op, points in pen.value:
        if op == "moveTo":
            ops.append(f"PathOp::Move({fmt(points[0][0])}, {fmt(points[0][1])})")
        elif op == "lineTo":
            ops.append(f"PathOp::Line({fmt(points[0][0])}, {fmt(points[0][1])})")
        elif op == "curveTo":
            assert len(points) == 3, f"unexpected curve in U+{code_point:04X}"
            flat = ", ".join(fmt(v) for point in points for v in point)
            ops.append(f"PathOp::Curve({flat})")
        elif op in ("closePath", "endPath"):
            ops.append("PathOp::Close")
        else:
            raise ValueError(f"unsupported operator {op} in U+{code_point:04X}")
    width = glyph_set[name].width
    return width, ops


def emit(const_name, comment, width, ops):
    print(f"/// {comment}")
    print(f"pub const {const_name}: Glyph = Glyph {{")
    print(f"    width: {fmt(width)},")
    print("    ops: &[")
    for op in ops:
        print(f"        {op},")
    print("    ],")
    print("};")
    print()


def main(path):
    font = TTFont(path)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()

    print("//! Music symbol outlines (clefs, hollow noteheads, accidentals, time signature digits).")
    print("//!")
    print("//! GENERATED by tools/extract_music_glyphs.py from the Bravura music font. Do not edit by hand.")
    print("//!")
    print("//! Bravura is Copyright (c) 2015, Steinberg Media Technologies GmbH,")
    print('//! with Reserved Font Name "Bravura", licensed under the SIL Open Font License 1.1')
    print("//! (see LICENSES/Bravura-OFL.txt).")
    print("//!")
    print("//! All coordinates are in staff spaces, y pointing up, following the SMuFL registration rules")
    print("//! (each glyph's origin is the point named in its doc comment).")
    print()
    print("/// One segment of a glyph outline.")
    print("#[derive(Debug, Clone, Copy, PartialEq)]")
    print("pub enum PathOp {")
    print("    Move(f32, f32),")
    print("    Line(f32, f32),")
    print("    /// Cubic Bezier: control point 1, control point 2, end point")
    print("    Curve(f32, f32, f32, f32, f32, f32),")
    print("    Close,")
    print("}")
    print()
    print("/// A filled glyph outline.")
    print("#[derive(Debug, Clone, Copy)]")
    print("pub struct Glyph {")
    print("    /// Horizontal advance in staff spaces")
    print("    pub width: f32,")
    print("    pub ops: &'static [PathOp],")
    print("}")
    print()

    for const_name, code_point, comment in GLYPHS:
        width, ops = outline(font, glyph_set, cmap, code_point)
        emit(const_name, f"{comment} (U+{code_point:04X})", width, ops)

    for const_name, code_point in DIGITS:
        width, ops = outline(font, glyph_set, cmap, code_point)
        emit(const_name, f"Time signature digit (U+{code_point:04X}), 2 spaces tall, centred on the origin", width, ops)

    print("/// Time signature digits 0 to 9, indexed by digit.")
    print("pub const TIME_SIG_DIGITS: [Glyph; 10] = [")
    for n in range(10):
        print(f"    TIME_SIG_{n},")
    print("];")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
